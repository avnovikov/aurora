import type { ExerciseType, MuscleEntry, Pattern } from "../../domain/types";
import type { LoadRegion, SeedExercise } from "../seed";

/**
 * Bodyweight moves common in Nike Training Club style workouts that the seed,
 * HF and free-exercise-db catalogues do not already cover. Only the move list
 * was referenced; names are generic and every cue is written in-house.
 */
export const NTC_ATTRIBUTION = "NTC-style bodyweight move (cues written in-house)";

interface NtcMove {
  id: string;
  name: string;
  pattern: Pattern;
  type: ExerciseType;
  muscles: MuscleEntry[];
  joints: string[];
  regions: LoadRegion[];
  cues: string[];
  role?: SeedExercise["role"];
  /** Timed interval (seconds) instead of counted reps. */
  timed?: boolean;
  easierId?: string;
  harderId?: string;
  description?: string;
  steps?: string[];
  mistakes?: string[];
  sources?: string[];
  difficulty?: SeedExercise["difficulty"];
}

const p = (group: MuscleEntry["group"]): MuscleEntry => ({ group, role: "primary" });
const s = (group: MuscleEntry["group"]): MuscleEntry => ({ group, role: "secondary" });
const st = (group: MuscleEntry["group"]): MuscleEntry => ({ group, role: "stabilizer" });

function ntc(move: NtcMove): SeedExercise {
  const { timed, role, description, ...rest } = move;
  return {
    ...rest,
    role: role ?? "work",
    ...(timed ? { effort: "hold" as const } : {}),
    description: description ?? move.cues.join(". ") + ".",
    attribution: NTC_ATTRIBUTION,
    sources: move.sources ?? [NTC_ATTRIBUTION],
  };
}

