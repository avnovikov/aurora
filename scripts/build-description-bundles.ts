/**
 * Gathers every source's text for each Library exercise (including the
 * duplicates skipped at import) into writer batches, and writes the
 * per-exercise source attribution module.
 *
 *   tsx scripts/build-description-bundles.ts <outDir> [batchCount]
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { LIBRARY_CATALOGUE } from "../src/data/libraryCatalogue.ts";
import { loadSourceCorpus } from "./load-source-corpus.ts";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");

async function main(): Promise<void> {
  const [outDir, batchArg] = process.argv.slice(2);
  if (!outDir) {
    throw new Error("usage: build-description-bundles.ts <outDir> [batchCount]");
  }
  const batchCount = Number(batchArg ?? 6);
  const corpus = await loadSourceCorpus(repoRoot);
  const byId = new Map(LIBRARY_CATALOGUE.map((item) => [item.id, item]));
  const nameOf = (id?: string): string | undefined => (id ? byId.get(id)?.name : undefined);
  const sourcesById: Record<string, string[]> = {};

  const bundles = LIBRARY_CATALOGUE.map((exercise) => {
    const source = corpus.get(exercise.id);
    if (!source) {
      throw new Error(`missing source corpus for ${exercise.id}`);
    }
    sourcesById[exercise.id] = [...new Set(source.texts.map((text) => text.source))];
    return {
      id: exercise.id,
      name: exercise.name,
      pattern: exercise.pattern,
      type: exercise.type,
      effort: exercise.effort ?? (exercise.type === "isometric" ? "hold" : "reps"),
      difficulty: exercise.difficulty,
      muscles: exercise.muscles.map((m) => `${m.group} (${m.role})`).join(", "),
      regions: exercise.regions,
      easier: nameOf(exercise.easierId),
      harder: nameOf(exercise.harderId),
      cautions: exercise.cautions ?? [],
      sourceTexts: source.texts.map(({ name, lines }) => ({ name, lines })),
    };
  });

  await mkdir(outDir, { recursive: true });
  const size = Math.ceil(bundles.length / batchCount);
  for (let index = 0; index < batchCount; index += 1) {
    const batch = bundles.slice(index * size, (index + 1) * size);
    await writeFile(path.join(outDir, `batch-${index + 1}.json`), JSON.stringify(batch, null, 1));
  }

  const modulePath = path.join(repoRoot, "src/data/generated/descriptionSources.ts");
  await writeFile(
    modulePath,
    `/** Generated by scripts/build-description-bundles.ts — sources merged into each description. */\nexport const DESCRIPTION_SOURCES: Record<string, string[]> = ${JSON.stringify(sourcesById, null, 2)};\n`,
  );
  const merged = bundles.filter((bundle) => bundle.sourceTexts.length > 1).length;
  console.log(`${bundles.length} bundles in ${batchCount} batches → ${outDir}; ${merged} merge text from 2+ sources`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
