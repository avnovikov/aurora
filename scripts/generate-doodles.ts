/**
 * Renders every spec in src/doodles/specs.ts to an animated SVG in
 * public/doodles/ and writes the exercise-id → path map the Library uses.
 *
 *   npm run doodles
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { renderDoodleSvg } from "../src/doodles/renderSvg.ts";
import { DOODLE_SPECS } from "../src/doodles/specs.ts";
import { validateSpec } from "../src/doodles/validate.ts";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function main(): Promise<void> {
  const invalid = DOODLE_SPECS.map(validateSpec).filter((report) => !report.ok);
  if (invalid.length > 0) {
    for (const report of invalid) console.error(`${report.slug}: ${report.errors.join("; ")}`);
    process.exitCode = 1;
    return;
  }
  const map: Record<string, string> = {};
  const replaced = DOODLE_SPECS.filter((spec) => spec.replaces).map((spec) => spec.id);
  for (const spec of DOODLE_SPECS) {
    const file = `doodle-${spec.slug}.svg`;
    await writeFile(path.join(repoRoot, "public/doodles", file), renderDoodleSvg(spec), "utf8");
    map[spec.id] = `/doodles/${file}`;
  }
  await writeFile(
    path.join(repoRoot, "src/data/generated/doodleMap.ts"),
    `/** Generated by scripts/generate-doodles.ts — animated SVG doodles by exercise id. */\nexport const GENERATED_DOODLES: Record<string, string> = ${JSON.stringify(map, null, 2)};\n\n/** Ids whose animation replaces a hand-drawn doodle (spec \`replaces: true\`). */\nexport const REPLACED_DOODLE_IDS: readonly string[] = ${JSON.stringify(replaced)};\n`,
    "utf8",
  );
  console.log(`Wrote ${DOODLE_SPECS.length} animated doodles to public/doodles/`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
