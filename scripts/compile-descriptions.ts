/**
 * Validates data/curated/descriptions/*.json and compiles them into
 * src/data/generated/descriptions.ts. Fails on any house-style problem.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { descriptionProblems } from "../src/data/describe/validate.ts";
import type { CuratedDescription } from "../src/data/describe/types.ts";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(repoRoot, "data/curated/descriptions");
const out = path.join(repoRoot, "src/data/generated/descriptions.ts");

async function main(): Promise<void> {
  const files = (await readdir(dir)).filter((file) => file.endsWith(".json")).sort();
  const byId: Record<string, CuratedDescription> = {};
  const problems: string[] = [];
  for (const file of files) {
    const entries = JSON.parse(await readFile(path.join(dir, file), "utf8")) as CuratedDescription[];
    for (const entry of entries) {
      if (byId[entry.id]) {
        problems.push(`${entry.id}: duplicate (${file})`);
      }
      for (const problem of descriptionProblems(entry)) {
        problems.push(`${entry.id}: ${problem} (${file})`);
      }
      byId[entry.id] = {
        id: entry.id,
        summary: entry.summary.trim(),
        steps: entry.steps.map((line) => line.trim()),
        cues: entry.cues.map((line) => line.trim()),
        mistakes: entry.mistakes.map((line) => line.trim()),
      };
    }
  }
  if (problems.length > 0) {
    console.error(problems.join("\n"));
    process.exitCode = 1;
    return;
  }
  const body = JSON.stringify(byId, null, 2);
  await writeFile(
    out,
    `import type { CuratedDescription } from "../describe/types";\n\n/** Generated by scripts/compile-descriptions.ts — edit data/curated/descriptions instead. */\nexport const DESCRIPTIONS: Record<string, CuratedDescription> = ${body};\n`,
  );
  console.log(`Compiled ${Object.keys(byId).length} descriptions from ${files.length} files`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
